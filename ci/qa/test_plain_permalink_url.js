'use strict';
const fs = require('fs');
const assert = require('assert');
const cp = require('child_process');
const path = process.argv[2];
assert(path, 'pass the exact 16.1.95 ZIP');
const source = cp.execFileSync('unzip', ['-p', path, 'stockland-erp-app/assets/app.js'], {encoding:'utf8'});
const start = source.indexOf('function resolveTrustedApiUrl(path,baseOverride){');
const end = source.indexOf('async function api(', start);
assert(start >= 0 && end > start, 'URL resolver is present in the package');
const resolver = new Function('A','window','URLSearchParams', source.slice(start,end) + '; return resolveTrustedApiUrl;');
const location = {href:'https://stockland.example/wp-admin/admin.php'};
const plain = {api:'https://stockland.example/?rest_route=/wp-json/stockland/v1', api_v16:'https://stockland.example/?rest_route=/wp-json/stockland/v16'};
const resolvePlain = resolver(plain,{location},URLSearchParams);
const u1 = new URL(resolvePlain('daily-closings/close?business_date=2026-10-24',plain.api));
assert.strictEqual(u1.searchParams.get('rest_route'),'/wp-json/stockland/v1/daily-closings/close');
assert.strictEqual(u1.searchParams.get('business_date'),'2026-10-24');
console.log('PASS plain-permalink rest_route and business_date query preserved');
const pretty = {api:'https://stockland.example/wp-json/stockland/v1',api_v16:'https://stockland.example/wp-json/stockland/v16'};
const resolvePretty = resolver(pretty,{location},URLSearchParams);
const u2 = new URL(resolvePretty('reports/dashboard?from=2026-10-01',pretty.api));
assert.strictEqual(u2.pathname,'/wp-json/stockland/v1/reports/dashboard');
assert.strictEqual(u2.searchParams.get('from'),'2026-10-01');
console.log('PASS pretty-permalink route and query preserved');
assert.throws(()=>resolvePlain('https://evil.example/wp-json/stockland/v1/products',plain.api), /Blocked ERP request/);
console.log('PASS absolute URLs outside configured WordPress REST origin rejected');
console.log('PLAIN PERMALINK QA: 3/3 PASS');
